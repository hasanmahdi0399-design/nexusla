-- Final access-control tightening. Run after 005_community_features.sql.

-- A recipient may only update the read marker on a direct message.
revoke update on public.messages from authenticated;
grant update(read_at) on public.messages to authenticated;
drop policy if exists messages_update_receiver on public.messages;
create policy messages_update_receiver on public.messages for update to authenticated
using (receiver_id=auth.uid()) with check (receiver_id=auth.uid());

-- Private profiles' posts are visible only to their owner and staff.
drop policy if exists posts_read on public.posts;
create policy posts_read on public.posts for select to authenticated
using (
  author_id=auth.uid() or public.is_staff() or exists(
    select 1 from public.profiles p where p.id=author_id and p.profile_visibility='public'
  )
);

-- Keep story visibility aligned with profile privacy.
drop policy if exists stories_read_active on public.stories;
create policy stories_read_active on public.stories for select to authenticated
using (
  expires_at>now() and (
    author_id=auth.uid() or public.is_staff() or exists(
      select 1 from public.profiles p where p.id=author_id and p.profile_visibility='public'
    )
  )
);

-- Do not let users create activity after their account is suspended/banned.
drop policy if exists comments_insert_self on public.comments;
create policy comments_insert_self on public.comments for insert to authenticated
with check (author_id=auth.uid() and public.is_active_user());
drop policy if exists listing_media_insert_owner on public.listing_media;
create policy listing_media_insert_owner on public.listing_media for insert to authenticated
with check (public.is_active_user() and exists(
  select 1 from public.listings l where l.id=listing_id and l.seller_id=auth.uid()
));

-- Revoke direct write access to moderation logs. Only privileged database routines write them.
revoke insert,update,delete on public.moderation_logs from authenticated,anon;

-- Comments and reactions must not bypass the visibility rules of their parent post.
drop policy if exists comments_read on public.comments;
create policy comments_read on public.comments for select to authenticated
using (exists(
  select 1 from public.posts p join public.profiles pr on pr.id=p.author_id
  where p.id=post_id and (p.author_id=auth.uid() or pr.profile_visibility='public' or public.is_staff())
));
drop policy if exists reactions_read on public.reactions;
create policy reactions_read on public.reactions for select to authenticated
using (exists(
  select 1 from public.posts p join public.profiles pr on pr.id=p.author_id
  where p.id=post_id and (p.author_id=auth.uid() or pr.profile_visibility='public' or public.is_staff())
));

-- Notifications are generated by trusted database triggers; clients may only mark them read.
revoke update on public.notifications from authenticated;
grant update(read) on public.notifications to authenticated;

-- Friend-request participants and timestamps are immutable after creation.
create or replace function public.protect_friend_request_fields()
returns trigger language plpgsql set search_path=public,pg_temp as $$
begin
  if new.requester_id <> old.requester_id or new.recipient_id <> old.recipient_id
     or new.created_at <> old.created_at then
    raise exception 'friend request participants cannot be changed';
  end if;
  new.updated_at := now();
  return new;
end; $$;
drop trigger if exists protect_friend_request_fields_trigger on public.friend_requests;
create trigger protect_friend_request_fields_trigger before update on public.friend_requests
for each row execute function public.protect_friend_request_fields();

-- Reviews are immutable after posting; a reviewer can remove and repost if needed.
revoke update on public.seller_reviews from authenticated;
